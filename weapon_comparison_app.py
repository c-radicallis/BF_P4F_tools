ROOT = Path(__file__).resolve().parent
HANDHELD_DIR = ROOT / "Handheld"
WEAPON_GEAR_DIR = ROOT / "WeaponGear"
NO_ATTACHMENT = "(None)"


# --------------------------------------------------
# Parsing and attachment processing
# --------------------------------------------------

def parse_con(filename):
    stats = {}
    text = filename.read_text(encoding="utf-8", errors="ignore")
    for line in text.splitlines():
        line = line.split("#")[0].strip()
        match = re.match(r"ObjectTemplate\.([\w.]+)\s+(.+)", line)
        if match:
            stats[match.group(1)] = match.group(2).strip()
    return stats


def parse_attachment(filename):
    stats = parse_con(filename)
    text = filename.read_text(encoding="utf-8", errors="ignore")
    description = filename.stem.replace("_", " ")

    ignored = (
        "DO NOT MODIFY", "AUTOGENERATED", "TRESPASSERS",
        "SURVIVORS", "WEAPONGEAR CON FILE"
    )
    for line in text.splitlines():
        match = re.match(r"\s*rem\s+(.+)", line, re.IGNORECASE)
        if match:
            value = match.group(1).strip()
            if value and not value.startswith("=") and not any(
                word in value.upper() for word in ignored
            ):
                description = value
                break
    return stats, description


def modifier_target(key):
    if not key.endswith("Mod"):
        return None
    name = key[:-3]
    prefixes = {
        "recoilComp": "recoil.",
        "deviationComp": "deviation.",
        "fireComp": "fire.",
        "ammoComp": "ammo.",
        "deviation": "deviation.",
        "recoil": "recoil.",
        "fire": "fire.",
        "ammo": "ammo.",
        "projectile": "",
    }
    for prefix, target_prefix in prefixes.items():
        if name.startswith(prefix):
            name = name[len(prefix):]
            return target_prefix + name[0].lower() + name[1:]
    return name[0].lower() + name[1:]


def add_values(base, modifier):
    if base.startswith("CRD_UNIFORM/") and modifier.startswith("CRD_UNIFORM/"):
        a = [float(v) for v in base.split("/")[1:]]
        b = [float(v) for v in modifier.split("/")[1:]]
        if len(a) != len(b):
            raise ValueError("Incompatible CRD_UNIFORM vectors")
        return "CRD_UNIFORM/" + "/".join(f"{x + y:g}" for x, y in zip(a, b))
    return str(float(base) + float(modifier))


def apply_attachments(base_stats, attachment_files):
    modified = base_stats.copy()
    for filename in attachment_files:
        if filename is None:
            continue
        attachment_stats, _ = parse_attachment(filename)
        for key, modifier in attachment_stats.items():
            if not key.startswith("upgradeWeapon."):
                continue
            target = modifier_target(key.replace("upgradeWeapon.", "", 1))
            if target and target in modified:
                try:
                    modified[target] = add_values(modified[target], modifier)
                except (ValueError, TypeError, AttributeError):
                    pass
    return modified


# --------------------------------------------------
# Discover weapons and attachments automatically
# --------------------------------------------------

def discover_weapons():
    weapons = {}
    if not HANDHELD_DIR.is_dir():
        return weapons

    for folder in sorted(p for p in HANDHELD_DIR.iterdir() if p.is_dir()):
        candidates = sorted(folder.rglob("*.con"))
        expected = folder / f"{folder.name}.con"
        weapon_file = expected if expected.is_file() else (
            candidates[0] if candidates else None
        )
        if weapon_file is None:
            continue
        weapon_type = folder.name.split("_", 1)[0]
        weapons.setdefault(weapon_type, []).append({
            "name": folder.name.replace("_", " "),
            "folder": folder.name,
            "file": weapon_file,
        })
    return weapons


def attachment_code_for_weapon_type(weapon_type):
    aliases = {
        "Srifle": "SR",
    }
    return aliases.get(weapon_type, weapon_type).upper()


def discover_attachments():
    attachments = {"Barrel": {}, "Ammo": {}, "Stock": {}}

    if not WEAPON_GEAR_DIR.is_dir():
        return attachments

    for filename in sorted(WEAPON_GEAR_DIR.rglob("*.con")):
        # Folder format: Barrel_SR_07, Ammo_LMG_11, Stock_AR_02
        parts = filename.parent.name.split("_")

        if len(parts) < 2:
            continue

        category, weapon_code = parts[0], parts[1].upper()

        if category not in attachments:
            continue

        try:
            _, description = parse_attachment(filename)
        except OSError:
            continue

        attachments[category].setdefault(weapon_code, {}).setdefault(
            description, []
        ).append(filename)

    # Build menus using attachment descriptions
    result = {category: {} for category in attachments}

    for category, weapon_groups in attachments.items():
        for weapon_code, entries in weapon_groups.items():
            result[category][weapon_code] = {}

            for description, files in entries.items():
                for filename in files:
                    label = (
                        description if len(files) == 1
                        else f"{description} ({filename.parent.name})"
                    )
                    result[category][weapon_code][label] = filename

    return result

