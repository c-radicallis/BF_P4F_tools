def get_number(stats, key, default=0.0):
    try:
        return float(stats.get(key, default))
    except (ValueError, TypeError):
        return default


def display(value, decimals=None):
    if value is None:
        return "N/A"
    try:
        number = float(value)
        if decimals is not None:
            return f"{number:.{decimals}f}"
        return str(int(number)) if number.is_integer() else f"{number:g}"
    except (ValueError, TypeError):
        return str(value).replace("CRD_UNIFORM/", "")


def ads_recoil(stats, key):
    value = stats.get(key)
    if value is None:
        return "N/A"
    zoom = get_number(stats, "recoil.zoomModifier", 1.0)
    try:
        values = [float(v) for v in value.replace("CRD_UNIFORM/", "").split("/")]
        return " / ".join(f"{v * zoom:.2f}" for v in values)
    except (ValueError, TypeError, AttributeError):
        return "N/A"


def comparison_rows(stats1, stats2):
    def weapon_rows(stats):
        rpm = get_number(stats, "fire.roundsPerMinute")
        mag = get_number(stats, "ammo.magSize")
        mags = get_number(stats, "ammo.nrOfMags")
        rows = {
            "Fire rate (RPM)": display(rpm),
            "Projectile velocity (m/s)": display(stats.get("velocity", "N/A")),
            "Magazine capacity": display(mag),
            "Number of magazines": display(mags),
            "Total ammunition": display(mag * mags),
            "Reload time (s)": display(stats.get("ammo.reloadTime", "N/A")),
            "Time between shots (s)": f"{60 / rpm:.4f}" if rpm else "N/A",
            "ADS recoil up": ads_recoil(stats, "recoil.recoilForceUp"),
            "ADS recoil left/right": ads_recoil(stats, "recoil.recoilForceLeftRight"),
        }
        deviation_keys = [
            ("Minimum deviation", "deviation.minDev"),
            ("Sub-projectile deviation", "deviation.subProjectileDev"),
            ("ADS deviation modifier", "deviation.DevModZoom"),
            ("ADS minimum deviation modifier", "deviation.minDevModZoom"),
            ("Set-fire deviation", "deviation.setFireDev"),
            ("Standing deviation modifier", "deviation.devModStand"),
            ("Crouching deviation modifier", "deviation.devModCrouch"),
        ]
        for label, key in deviation_keys:
            rows[label] = display(stats.get(key, "N/A"))
        return rows

    rows1, rows2 = weapon_rows(stats1), weapon_rows(stats2)
    return [(key, rows1.get(key, "N/A"), rows2.get(key, "N/A")) for key in rows1]


def damage_data(stats):
    distances = [
        0,
        get_number(stats, "mediumDistance"),
        get_number(stats, "longDistance"),
    ]
    dmin = [
        get_number(stats, "initialMinDamage"),
        get_number(stats, "mediumMinDamage"),
        get_number(stats, "longMinDamage"),
    ]
    dmax = [
        get_number(stats, "initialMaxDamage"),
        get_number(stats, "mediumMaxDamage"),
        get_number(stats, "longMaxDamage"),
    ]
    end_distance = max(40, distances[-1] * 1.3)
    return distances + [end_distance], dmin + [dmin[-1]], dmax + [dmax[-1]]


# --------------------------------------------------
# Desktop application
# --------------------------------------------------

class WeaponComparisonApp:
    def __init__(self, root):
        self.root = root
        self.root.title("Battlefield Play4Free - Weapon Comparison")
        self.root.geometry("1600x900")
        self.weapons = discover_weapons()
        self.attachments = discover_attachments()
        self.weapon_controls = []

        if not self.weapons:
            messagebox.showerror(
                "Weapon files not found",
                f"No weapon .con files were found under:\n{HANDHELD_DIR}"
            )
            root.destroy()
            return

        self.build_interface()
        self.refresh_all()

    def build_interface(self):
        outer = ttk.Frame(self.root, padding=10)
        outer.pack(fill="both", expand=True)

        selectors = ttk.Frame(outer)
        selectors.pack(fill="x", pady=(0, 8))

        for index in range(2):
            frame = ttk.LabelFrame(selectors, text=f"Weapon {index + 1}", padding=10)
            frame.pack(side="left", fill="both", expand=True, padx=(0 if index == 0 else 8, 0))
            controls = {}

            ttk.Label(frame, text="Weapon type").grid(row=0, column=0, sticky="w", padx=4, pady=3)
            type_box = ttk.Combobox(
                frame, state="readonly", width=18,
                values=sorted(self.weapons)
            )
            type_box.grid(row=0, column=1, sticky="ew", padx=4, pady=3)
            type_box.bind("<<ComboboxSelected>>", lambda _e, i=index: self.on_type_changed(i))
            controls["type"] = type_box

            ttk.Label(frame, text="Weapon").grid(row=1, column=0, sticky="w", padx=4, pady=3)
            weapon_box = ttk.Combobox(frame, state="readonly", width=28)
            weapon_box.grid(row=1, column=1, sticky="ew", padx=4, pady=3)
            weapon_box.bind("<<ComboboxSelected>>", lambda _e: self.refresh_all())
            controls["weapon"] = weapon_box

            for row, category in enumerate(("Barrel", "Ammo", "Stock"), start=2):
                ttk.Label(frame, text=category).grid(row=row, column=0, sticky="w", padx=4, pady=3)
                box = ttk.Combobox(
                    frame, state="readonly", width=28,
                    values=[NO_ATTACHMENT]
                )
                box.current(0)
                box.grid(row=row, column=1, sticky="ew", padx=4, pady=3)
                box.bind("<<ComboboxSelected>>", lambda _e: self.refresh_all())
                controls[category] = box

            frame.columnconfigure(1, weight=1)
            self.weapon_controls.append(controls)
            type_box.current(0)
            self.on_type_changed(index, refresh=False)

        ttk.Button(outer, text="Refresh comparison", command=self.refresh_all).pack(anchor="e", pady=(0, 8))

        plot_frame = ttk.LabelFrame(outer, text="Damage vs Range", padding=5)
        plot_frame.pack(fill="both", expand=True, pady=(0, 8))

        self.fig, self.ax = plt.subplots(figsize=(10, 4.2), dpi=100)
        self.fig.subplots_adjust(left=0.08, right=0.98, top=0.90, bottom=0.13)
        self.canvas = FigureCanvasTkAgg(self.fig, master=plot_frame)
        self.canvas.get_tk_widget().pack(fill="both", expand=True)

        table_frame = ttk.LabelFrame(outer, text="Weapon Statistics Comparison", padding=5)
        table_frame.pack(fill="both", expand=True)

        columns = ("parameter", "weapon1", "weapon2")
        self.tree = ttk.Treeview(table_frame, columns=columns, show="headings", height=14)
        self.tree.heading("parameter", text="Parameter")
        self.tree.heading("weapon1", text="Weapon 1")
        self.tree.heading("weapon2", text="Weapon 2")
        self.tree.column("parameter", width=330, anchor="w")
        self.tree.column("weapon1", width=360, anchor="center")
        self.tree.column("weapon2", width=360, anchor="center")
        scrollbar = ttk.Scrollbar(table_frame, orient="vertical", command=self.tree.yview)
        self.tree.configure(yscrollcommand=scrollbar.set)
        self.tree.pack(side="left", fill="both", expand=True)
        scrollbar.pack(side="right", fill="y")

    def on_type_changed(self, index, refresh=True):
        controls = self.weapon_controls[index]
        weapon_type = controls["type"].get()
        options = self.weapons.get(weapon_type, [])
        labels = [item["name"] for item in options]

        controls["weapon"]["values"] = labels

        if labels:
            controls["weapon"].current(0)

        self.update_attachment_options(index)

        if refresh:
            self.refresh_all()


    def update_attachment_options(self, index):
        controls = self.weapon_controls[index]
        weapon_code = attachment_code_for_weapon_type(
            controls["type"].get()
        )

        for category in ("Barrel", "Ammo", "Stock"):
            available = self.attachments[category].get(weapon_code, {})
            values = [NO_ATTACHMENT] + list(available)

            box = controls[category]
            previous = box.get()

            box["values"] = values

            if previous in values:
                box.set(previous)
            else:
                box.current(0)
                
    def selected_weapon(self, index):
        controls = self.weapon_controls[index]
        selected_name = controls["weapon"].get()
        weapon_type = controls["type"].get()
        for item in self.weapons.get(weapon_type, []):
            if item["name"] == selected_name:
                return item
        return None

    def selected_stats(self, index):
        weapon = self.selected_weapon(index)
        if weapon is None:
            return {}, "No weapon selected"

        stats = parse_con(weapon["file"])
        controls = self.weapon_controls[index]
        chosen = []

        weapon_code = attachment_code_for_weapon_type(
            controls["type"].get()
        )

        for category in ("Barrel", "Ammo", "Stock"):
            label = controls[category].get()

            category_options = self.attachments[category].get(
                weapon_code, {}
            )

            filename = (
                category_options.get(label)
                if label != NO_ATTACHMENT else None
            )

            if filename:
                chosen.append(filename)

        stats = apply_attachments(stats, chosen)
        attachment_labels = [
            controls[category].get()
            for category in ("Barrel", "Ammo", "Stock")
            if controls[category].get() != NO_ATTACHMENT
        ]
        title = weapon["name"]
        if attachment_labels:
            title += " [" + ", ".join(attachment_labels) + "]"
        return stats, title

    def refresh_all(self):
        try:
            stats1, title1 = self.selected_stats(0)
            stats2, title2 = self.selected_stats(1)
            self.update_plot(stats1, stats2, title1, title2)
            self.update_table(stats1, stats2)
        except Exception as exc:
            messagebox.showerror("Could not update comparison", str(exc))

    def update_plot(self, stats1, stats2, title1, title2):
        self.ax.clear()

        for stats, title, style, colour in (
            (stats1, title1, "-", "tab:blue"),
            (stats2, title2, "--", "tab:orange"),
        ):
            distances, damage_min, damage_max = damage_data(stats)

            self.ax.fill_between(
                distances, damage_min, damage_max,
                step="post", alpha=0.12, color=colour
            )

            self.ax.step(
                distances, damage_max, where="post",
                linestyle=style, linewidth=2, color=colour,
                label=f"{title}"
            )

            self.ax.step(
                distances, damage_min, where="post",
                linestyle=style, linewidth=2, color=colour#,
                #label=f"{title} - Min"
            )

            # Annotate damage ranges
            for d, dmin, dmax in zip(
                distances[:-1], damage_min[:-1], damage_max[:-1]
            ):
                self.ax.annotate(
                    f"{dmin:g}–{dmax:g}",
                    (d, dmax),
                    xytext=(5, 5),
                    textcoords="offset points",
                    fontsize=8
                )

        self.ax.set_title("Damage vs Range")
        self.ax.set_xlabel("Range (m)")
        self.ax.set_ylabel("Damage")
        self.ax.set_xlim(left=0)
        self.ax.set_ylim(bottom=0)
        self.ax.grid(True, alpha=0.3)
        self.ax.legend(fontsize=8)
        self.ax.set_xticks(range(0, int(self.ax.get_xlim()[1]) + 1, 5))
        self.canvas.draw_idle()

    def update_table(self, stats1, stats2):
        for item in self.tree.get_children():
            self.tree.delete(item)
        for row in comparison_rows(stats1, stats2):
            self.tree.insert("", "end", values=row)


if __name__ == "__main__":
    root = tk.Tk()
    app = WeaponComparisonApp(root)
    if root.winfo_exists():
        root.mainloop()
