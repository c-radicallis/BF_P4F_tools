# --------------------------------------------------
# Parsing functions
# --------------------------------------------------

def parse_con(filename):
    text = filename.read_text(encoding="utf-8", errors="ignore")
    stats = {}

    for line in text.splitlines():
        line = line.split("#")[0].strip()
        match = re.match(r"ObjectTemplate\.([\w.]+)\s+(.+)", line)

        if match:
            stats[match.group(1)] = match.group(2).strip()

    return stats


def parse_attachment(filename):
    stats = parse_con(filename)
    text = filename.read_text(encoding="utf-8", errors="ignore")

    # Extract attachment description from rem comments
    description = filename.stem

    for line in text.splitlines():
        match = re.match(r"\s*rem\s+(.+)", line, re.IGNORECASE)

        if match:
            value = match.group(1).strip()

            if value and not value.startswith("="):
                if not any(word in value.upper() for word in [
                    "DO NOT MODIFY", "AUTOGENERATED",
                    "TRESPASSERS", "SURVIVORS",
                    "WEAPONGEAR CON FILE"
                ]):
                    description = value
                    break

    return stats, description


def display(value):
    try:
        n = float(value)
        return str(int(n)) if n.is_integer() else f"{n:g}"
    except (ValueError, TypeError):
        return str(value) if value is not None else "N/A"


def clean_value(value):
    return str(value).replace("CRD_UNIFORM/", "")


# --------------------------------------------------
# Attachment modifier processing
# --------------------------------------------------

def modifier_target(key):
    """
    Convert an upgradeWeapon modifier name into
    its corresponding base weapon property.

    Examples:
    projectileInitialMinDamageMod -> initialMinDamage
    projectileLongDistanceMod -> longDistance
    recoilCompZoomModifierMod -> recoil.zoomModifier
    deviationCompMinDevMod -> deviation.minDev
    velocityMod -> velocity
    """

    if not key.endswith("Mod"):
        return None

    name = key[:-3]

    prefixes = {
        "recoilComp": "recoil.",
        "deviationComp": "deviation.",
        "fireComp": "fire.",
        "ammoComp": "ammo.",
        "deviation": "deviation.",
        "recoil": "recoil.",
        "fire": "fire.",
        "ammo": "ammo.",
        "projectile": "",
    }

    for prefix, target_prefix in prefixes.items():
        if name.startswith(prefix):
            name = name[len(prefix):]
            return target_prefix + name[0].lower() + name[1:]

    return name[0].lower() + name[1:]


def add_values(base, modifier):
    """Add numeric values or CRD_UNIFORM vectors."""

    # CRD_UNIFORM vector addition
    if base.startswith("CRD_UNIFORM/") and modifier.startswith("CRD_UNIFORM/"):
        a = [float(v) for v in base.split("/")[1:]]
        b = [float(v) for v in modifier.split("/")[1:]]

        if len(a) != len(b):
            raise ValueError("Incompatible CRD_UNIFORM vectors")

        result = [x + y for x, y in zip(a, b)]

        return "CRD_UNIFORM/" + "/".join(
            f"{v:g}" for v in result
        )

    # Numeric addition
    return str(float(base) + float(modifier))


def apply_attachments(base_stats, attachment_files):
    """
    Apply all attachment modifiers cumulatively.
    Original weapon statistics remain unchanged.
    """

    modified = base_stats.copy()
    attachment_names = []
    applied = []
    warnings = []

    for filename in attachment_files:
        if not filename.exists():
            warnings.append(f"Attachment not found: {filename}")
            continue

        attachment_stats, description = parse_attachment(filename)
        attachment_names.append(description)

        for key, modifier in attachment_stats.items():

            if not key.startswith("upgradeWeapon."):
                continue

            mod_name = key.replace("upgradeWeapon.", "", 1)
            target = modifier_target(mod_name)

            if target is None:
                continue

            if target not in modified:
                warnings.append(
                    f"{filename.name}: property not found: {target}"
                )
                continue

            try:
                modified[target] = add_values(
                    modified[target], modifier
                )

                applied.append((description, target, modifier))

            except (ValueError, TypeError, AttributeError):
                warnings.append(
                    f"{filename.name}: could not apply "
                    f"{mod_name} = {modifier} to {target}"
                )

    return modified, attachment_names, applied, warnings


