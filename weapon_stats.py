# --------------------------------------------------

if BATCH_MODE:
    files = sorted(Path(".").glob("*.con"))
else:
    files = [FILE]

if not files:
    print("No .con files found.")

for file in files:
    print(f"\nProcessing {file.name}...")

    try:
        # 1. Original weapon report
        base_stats = parse_con(file)

        generate_report(
            file,
            base_stats,
            suffix="" #"_base"
        )

        # 2. Modified weapon report, if attachments exist
        attachment_files = ATTACHMENTS.get(file.name, [])

        if attachment_files:
            modified_stats, attachment_names, applied, warnings = (
                apply_attachments(base_stats, attachment_files)
            )

            generate_report(
                file,
                modified_stats,
                suffix="_"+"_".join(attachment_names),
                attachment_names=attachment_names
            )

            print(f"Attachments: {', '.join(attachment_names)}")
            print(f"Modifiers applied: {len(applied)}")

            for warning in warnings:
                print(f"WARNING: {warning}")

    except Exception as e:
        print(f"Error processing {file.name}: {e}")
